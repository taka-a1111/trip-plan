def mv(name, dur, plan=None, toll=None, note=None, badges=None):
    r = {"type": "move", "name": name, "dur": dur}
    if plan: r["plan"] = plan
    if toll: r["toll"] = toll
    if note:
        r["note"] = note
        r["keep_note"] = True
    if badges: r["badges"] = badges
    return r


